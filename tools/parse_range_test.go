// TestParseRangeOutOfRange 测试超出范围的值
func TestParseRangeOutOfRange(t *testing.T) {
	totalLines := 10
	
	tests := []struct {
		name     string
		rangeStr string
	}{
		{
			name:     "negative start",
			rangeStr: "-1:5",
		},
		{
			name:     "negative end",
			rangeStr: "1:-5",
		},
	}
	
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Note: Negative values will be handled by parseLineNumber
			// This test is more about ensuring parseRange handles these correctly
			_, _, err := parseRange(tt.rangeStr, totalLines)
			start, end, err := parseRange(tt.rangeStr, totalLines)
			// This might not error depending on how parseLineNumber handles it
			// We're just ensuring the function doesn't panic
			_ = start
			_ = end
			_ = err
		})
	}
}