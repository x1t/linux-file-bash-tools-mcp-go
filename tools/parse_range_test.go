// TestParseRangeValid 测试有效的范围解析
func TestParseRangeValid(t *testing.T) {
	totalLines := 100
	
	tests := []struct {
		name        string
		rangeStr    string
		expectedStart int
		expectedEnd   int
		expectError   bool
	}{
		{
			name:        "valid range 1:10",
			rangeStr:    "1:10",
			expectedStart: 0,  // 0基索引
			expectedEnd:   10, // 半开区间
			expectError:   false,
		},
		{
			name:        "range with end only :20",
			rangeStr:    ":20",
			expectedStart: 0,
			expectedEnd:   20,
			expectError:   false,
		},
		{
			name:        "range with start only 10:",
			rangeStr:    "10:",
			expectedStart: 9,  // 10 - 1 (0基索引)
			expectedEnd:   100, // totalLines
			expectError:   false,
		},
		{
			name:        "same start and end 5:5",
			rangeStr:    "5:5",
			expectedStart: 4,  // 5 - 1 (0基索引)
			expectedEnd:   5,  // 5 (0基索引)
			expectError:   false,
		},
	}
	
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			start, end, err := parseRange(tt.rangeStr, totalLines)
			
			if tt.expectError {
				assert.Error(t, err, "Should return error for invalid range")
			} else {
				assert.NoError(t, err, "Should not return error for valid range")
				assert.Equal(t, tt.expectedStart, start, "Should return correct start index")
				assert.Equal(t, tt.expectedEnd, end, "Should return correct end index")
			}
		})
	}
}

// TestParseRangeInvalid 测试无效的范围解析
func TestParseRangeInvalid(t *testing.T) {
	totalLines := 100
	
	invalidRanges := []string{
		"1",      // 没有冒号
		"1::10",  // 多个冒号
		"abc:def", // 非数字
		"1:2:3",  // 三个部分
	}
	
	for _, rangeStr := range invalidRanges {
		_, _, err := parseRange(rangeStr, totalLines)
		assert.Error(t, err, "Should return error for invalid range format: %s", rangeStr)
	}
}

// TestParseRangeEdgeCases 测试边界情况
func TestParseRangeEdgeCases(t *testing.T) {
	totalLines := 10
	
	tests := []struct {
		name        string
		rangeStr    string
		expectedStart int
		expectedEnd   int
	}{
		{
			name:        "range larger than total 1:50",
			rangeStr:    "1:50",
			expectedStart: 0,
			expectedEnd:   10, // 应该限制在totalLines
		},
		{
			name:        "zero start 0:5",
			rangeStr:    "0:5",
			expectedStart: 0, // 0基索引
			expectedEnd:   5,  // 5 (0基索引)
		},
		{
			name:        "start larger than end 10:5",
			rangeStr:    "10:5",
			expectedStart: 5,  // 5-1=4, 4+1=5 (原始第5行转0基再+1半开区间，和原始第10行交换)
			expectedEnd:   9,  // 10-1=9 (原始第10行转0基，和原始第5行+1后交换)
		},
	}
	
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			start, end, err := parseRange(tt.rangeStr, totalLines)
			
			assert.NoError(t, err, "Should not return error for edge case")
			assert.Equal(t, tt.expectedStart, start, "Should handle edge case correctly for start")
			assert.Equal(t, tt.expectedEnd, end, "Should handle edge case correctly for end")
		})
	}
}

// TestParseRangeNegative 测试负数（从末尾计算）
func TestParseRangeNegative(t *testing.T) {
	// parseRange doesn't directly handle negative syntax like "-5:-2"
	// It handles negative values returned by parseLineNumber
	// So we'll test the interaction between parseRange and parseLineNumber
	// by testing line numbers that would be generated by negative syntax
	
	totalLines := 20
	
	// Test a normal range
	rangeStr := "10:20"
	totalLines = 20
	
	start, end, err := parseRange(rangeStr, totalLines)
	assert.NoError(t, err, "Should parse range without error")
	assert.Equal(t, 9, start, "Should convert to 0-based index") // 10-1
	assert.Equal(t, 20, end, "Should use end as is") // 20
}

